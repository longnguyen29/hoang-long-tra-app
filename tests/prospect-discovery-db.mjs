// Run with PGLITE_MODULE pointing to an installed PGlite module, then pass the migration path.
const { PGlite } = await import(process.env.PGLITE_MODULE || '@electric-sql/pglite');
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const db = new PGlite();
const manager = '00000000-0000-0000-0000-000000000001';
const worker = '00000000-0000-0000-0000-000000000002';
await db.exec(`create role anon; create role authenticated; create role service_role;
create schema auth; create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('app.uid',true),'')::uuid $$;
grant usage on schema auth to authenticated; grant execute on function auth.uid() to authenticated;
create table staff_roles(user_id uuid primary key, role text);
insert into auth.users values('${manager}'),('${worker}');
insert into staff_roles values('${manager}','manager'),('${worker}','worker');
create function public.is_staff_manager() returns boolean language sql security definer set search_path=public as $$select exists(select 1 from staff_roles where user_id=auth.uid() and role in ('admin','manager'))$$;`);
await db.exec(await fs.readFile(process.argv[2],'utf8'));
await db.exec(`set role authenticated; set app.uid='${worker}'`);
assert.equal((await db.query('select * from discovery_prospects')).rows.length,0);
await assert.rejects(db.query(`insert into discovery_prospects(name,source_url,source_key,evidence_kind) values('x','https://cafe.vn','cafe.vn','page_review')`));
await db.exec(`set app.uid='${manager}'`);
const {rows:[p]}=await db.query(`insert into discovery_prospects(name,source_url,source_key,evidence_kind) values('x','https://cafe.vn','cafe.vn','page_review') returning *`);
await assert.rejects(db.query(`insert into discovery_prospects(name,source_url,source_key,evidence_kind) values('x','https://cafe.vn','cafe.vn','page_review')`));
await assert.rejects(db.query(`update discovery_prospects set status='qualified'`));
await assert.rejects(db.query(`truncate discovery_prospects`));
await db.query(`select review_discovery_prospect($1,1,'qualified','verified','','Cafe','Hà Nội','trà sữa',true)`,[p.id]);
await assert.rejects(db.query(`select review_discovery_prospect($1,1,'research','stale','','Cafe','','',false)`,[p.id]),/stale_prospect/);
await db.query(`select review_discovery_prospect($1,2,'do_not_contact','declined','','Cafe','','',true)`,[p.id]);
assert.equal((await db.query('select status,version from discovery_prospects')).rows[0].version,3);
await assert.rejects(db.query(`select reserve_discovery_search($1,'test',1)`,[manager]));
await db.exec(`set app.uid='${worker}'`);
assert.equal((await db.query('select * from discovery_prospects')).rows.length,0);
await assert.rejects(db.query(`select review_discovery_prospect($1,3,'qualified','','','Cafe','','',true)`,[p.id]),/manager_required/);
await db.exec('reset role; set role service_role');
await db.query(`select reserve_discovery_search($1,'test',1)`,[manager]);
await assert.rejects(db.query(`select reserve_discovery_search($1,'test2',1)`,[manager]),/daily_limit/);
console.log('PASS: manager access, worker isolation, duplicate prevention, CAS stale edit, suppression, service-only shared daily limit');
await db.close();
